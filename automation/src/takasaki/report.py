"""Migration report (DESIGN.md §12 M7): every difference between the current legacy files and a
fresh build from the migrated data, plus the review items a person has to decide."""

from __future__ import annotations

import csv
import io
import json
from collections import Counter, defaultdict
from pathlib import Path

from .build_legacy import ALBUM_HEADER, MEMBER_HEADER, build_legacy
from .migrate_legacy import MigrationResult
from .store import _to_node, _yaml


def _csv_rows(blob: bytes) -> list[list[str]]:
    return list(csv.reader(io.StringIO(blob.decode("utf-8-sig"))))


def csv_cell_diff(old: bytes, new: bytes, header: list[str]) -> list[str]:
    a, b = _csv_rows(old), _csv_rows(new)
    lines = []
    if len(a) != len(b):
        lines.append(f"row count {len(a) - 1} → {len(b) - 1}")
    for i, (ra, rb) in enumerate(zip(a, b)):
        for k, (x, y) in enumerate(zip(ra, rb)):
            if x != y:
                label = ra[0] if header is ALBUM_HEADER else ra[0]
                lines.append(f"row {i} `{label}` #{ra[1] if header is ALBUM_HEADER else ''} {header[k]}: `{x}` → `{y}`")
    return lines


def json_entry_diff(old: bytes, new: bytes) -> tuple[int, int, int]:
    a, b = json.loads(old), json.loads(new)
    if isinstance(a, dict):
        a, b = a["data"], b["data"]
    ca = Counter(json.dumps(x, ensure_ascii=False, sort_keys=True) for x in a)
    cb = Counter(json.dumps(x, ensure_ascii=False, sort_keys=True) for x in b)
    return len(a), sum((ca - cb).values()), sum((cb - ca).values())


def write_reviews(res: MigrationResult, review_dir: Path) -> list[Path]:
    review_dir.mkdir(parents=True, exist_ok=True)
    for old in review_dir.glob("MIG-*.yaml"):
        old.unlink()
    counters: Counter[str] = Counter()
    paths = []
    for rv in res.reviews:
        counters[rv.kind] += 1
        path = review_dir / f"MIG-{rv.kind}-{counters[rv.kind]:03d}.yaml"
        doc = {"type": rv.kind, "title": rv.title, "note": rv.note or None, "items": rv.items, "decision": None}
        doc = {k: v for k, v in doc.items() if v is not None or k == "decision"}
        buf = io.StringIO()
        _yaml().dump(_to_node(doc), buf)
        path.write_text(buf.getvalue(), encoding="utf-8")
        paths.append(path)
    return paths


def write_migration_report(root: Path, res: MigrationResult, review_dir: Path) -> Path:
    files = build_legacy(res.ds)
    ds = res.ds
    out = ["# legacy → canonical migration report", ""]
    out.append("Generated by `takasaki migrate`. Lists every difference between the legacy files before the")
    out.append("migration and a fresh build from `data/`, and the review items that need a decision.")
    out.append("")
    out.append("## Entities")
    out.append("")
    for name in ("projects", "persons", "characters", "artists", "works", "releases", "cities", "venues", "concerts"):
        out.append(f"- {name}: {len(getattr(ds, name))}")
    out.append(f"- recordings: {sum(len(w.recordings) for w in ds.works.values())}")
    out.append(f"- tracks: {sum(len(d.tracks) for r in ds.releases.values() for d in r.discs)}")
    out.append("")
    out.append("## Output differences")
    out.append("")
    identical, changed = [], []
    for rel, blob in sorted(files.items()):
        path = root / rel
        old = path.read_bytes() if path.exists() else b""
        (identical if old == blob else changed).append(rel)
    out.append(f"{len(identical)} of {len(files)} legacy files are byte-identical.")
    out.append("")
    for rel in changed:
        old = (root / rel).read_bytes() if (root / rel).exists() else b""
        new = files[rel]
        out.append(f"### `{rel}`")
        out.append("")
        if rel.endswith(".csv"):
            header = ALBUM_HEADER if rel.startswith("albums/") else MEMBER_HEADER
            for line in csv_cell_diff(old, new, header):
                out.append(f"- {line}")
        elif old:
            n, removed, added = json_entry_diff(old, new)
            if rel == "TakasakiInfo.json":
                a, b = json.loads(old), json.loads(new)
                if a["dbLastUpdate"] != b["dbLastUpdate"]:
                    out.append(f"- dbLastUpdate: `{a['dbLastUpdate']}` → `{b['dbLastUpdate']}`")
            out.append(f"- {n} entries; {removed} removed or changed, {added} added or changed"
                       " (same causes as the CSV changes above; duplicates removed per §10.1 #1)")
        else:
            out.append("- new file")
        out.append("")
    out.append("## Applied changes by kind")
    out.append("")
    grouped: dict[str, Counter[str]] = defaultdict(Counter)
    for c in res.changes:
        grouped[c.kind][f"{c.where}: {c.detail}"] += 1
    for kind, items in sorted(grouped.items()):
        out.append(f"### {kind} ({sum(items.values())})")
        out.append("")
        for text, n in sorted(items.items()):
            out.append(f"- {text}" + (f" ×{n}" if n > 1 else ""))
        out.append("")
    paths = write_reviews(res, review_dir)
    out.append("## Review items")
    out.append("")
    out.append(f"{len(paths)} files under `automation/review/`. Fill in `decision` in each file.")
    out.append("")
    by_kind = Counter(rv.kind for rv in res.reviews)
    for kind, n in sorted(by_kind.items()):
        out.append(f"- {kind}: {n}")
    out.append("")
    report = root / "automation" / "migration" / "REPORT.md"
    report.parent.mkdir(parents=True, exist_ok=True)
    report.write_text("\n".join(out), encoding="utf-8")
    return report
